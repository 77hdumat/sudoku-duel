type RC = [number, number];
export interface Diagram {
  /** 옅게 칠할 유닛 칸 */
  area?: RC[];
  /** 굵은 테두리 칸 */
  cells?: RC[];
  /** 후보 동그라미 [행, 열, 글자, 색] */
  dots?: [number, number, string, 'key' | 'on' | 'off'][];
  /** 이미 놓인 숫자 */
  digits?: [number, number, string][];
  /** 지우는 자리 */
  x?: RC[];
  /** 연결선 [from, to, 강한 연결?] */
  lines?: [RC, RC, boolean][];
}

export interface Tech {
  name: string;
  /** 나무위키 분류 */
  tier: '기초' | '초급' | '중급' | '고급' | '초고급';
  idea: string;
  spot: string;
  result: string;
  /** 외우기 한 줄 */
  memo: string;
  diagram: Diagram;
}

const row = (r: number): RC[] => Array.from({ length: 9 }, (_, c) => [r, c]);
const col = (c: number): RC[] => Array.from({ length: 9 }, (_, r) => [r, c]);
const box = (b: number): RC[] => Array.from({ length: 9 }, (_, k) => [Math.floor(b / 3) * 3 + Math.floor(k / 3), (b % 3) * 3 + (k % 3)]);

